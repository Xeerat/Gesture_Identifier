def get_pattern(name: str) -> str:
    """
    Возвращает упакованную шестнадцатеричную битовую карту (bitmap) для заданного жеста.

    Автоматически нормализует входную строку (приводит к нижнему регистру и удаляет
    лишние пробелы по краям) перед поиском в реестре доступных паттернов `GESTURE_PATTERNS`.

    Args:
        name (str): Название жеста (например, "rock", "paper", "idle").

    Returns:
        str: Строка с шестнадцатеричным представлением битовой карты, готовая
             для прямой отправки на OLED-дисплей.

    Raises:
        ValueError: Если переданное имя жеста отсутствует в реестре `GESTURE_PATTERNS`,
                    или если аргумент `name` не является строкой (например, передан `None`).
                    Исключение сохраняет цепочку причин (exception chaining) для удобной отладки.
    """
    try:
        return GESTURE_PATTERNS[name.lower().strip()]
    except (AttributeError, KeyError) as exc:
        raise ValueError(f"Unknown gesture: {name!r}") from exc
