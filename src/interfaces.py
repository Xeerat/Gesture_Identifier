from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass

import numpy as np


# ============================================================
# Результат детекции
# ============================================================
@dataclass
class DetectionResult:
    """
    Стандартизированный результат распознавания жеста.

    Используется как единый формат возврата данных от любого детектора
    (YOLO, MediaPipe, заглушки) к главному циклу приложения. Это гарантирует,
    что не придется переписывать логику обработки при смене модели.
    """

    gesture: str
    """Название распознанного жеста (должно совпадать с классом из config.model.classes)."""

    confidence: float
    """Уровень уверенности модели в диапазоне от 0.0 до 1.0."""

    bbox: tuple[int, int, int, int] | None = None
    """Опциональные координаты ограничивающей рамки (x1, y1, x2, y2)."""

    @property
    def is_valid(self) -> bool:
        """
        Проверяет, был ли успешно распознан осмысленный жест.

        Returns:
            bool: True, если жест распознан и не является "none" или пустой строкой.
        """
        return self.gesture not in (None, "", "none")

    def __str__(self) -> str:
        """
        Возвращает строковое представление результата для удобного логирования.

        Returns:
            str: Форматированная строка с названием жеста и уверенностью (2 знака).
        """
        return f"Detection(gesture={self.gesture}, conf={self.confidence:.2f})"


# ============================================================
# Детектор
# ============================================================
class DetectorInterface(ABC):
    """
    Базовый интерфейс (контракт) для всех модулей распознавания жестов.

    Любой класс, реализующий этот интерфейс (например, RKNN-детектор от
    ML-инженера или заглушка для тестов), обязан предоставить методы для
    инференса и получения списка поддерживаемых классов.
    """

    @abstractmethod
    def detect(self, frame: np.ndarray) -> DetectionResult:
        """
        Выполняет распознавание жеста на переданном кадре.

        Args:
            frame (np.ndarray): Входное изображение в цветовом пространстве BGR
                                с формой (Height, Width, 3).

        Returns:
            DetectionResult: Объект, содержащий распознанный жест, уровень
                             уверенности и опциональные координаты рамки.
                             Если жест не найден, возвращает gesture="none".
        """

    @abstractmethod
    def close(self) -> None:
        """
        Освобождает ресурсы, занятые детектором (память NPU, контекст модели).

        По умолчанию не делает ничего. Должен быть переопределен, если
        детектор выделяет внешние ресурсы, требующие явного освобождения.
        """

    @abstractmethod
    def warmup(self, frames_count: int = 10) -> None:
        """
        Выполняет прогрев модели перед началом основной работы.

        Полезно для инициализации NPU или выделения памяти.
        По умолчанию не делает ничего (no-op), переопределяется в реализациях.

        Args:
            frames_count (int, optional): Количество фиктивных кадров для прогрева.
                                          По умолчанию 10.
        """


# ============================================================
# Контроллер LED-ленты
# ============================================================
class LEDControllerInterface(ABC):
    """
    Базовый интерфейс (контракт) для управления светодиодной лентой.

    Абстрагирует работу с конкретным hardware (SPI, I2C, GPIO),
    позволяя главному приложению управлять лентой, не зная деталей
    низкоуровневой реализации.
    """

    @abstractmethod
    def show_gesture(self, gesture_name: str) -> None:
        """
        Отображает визуальный паттерн, соответствующий распознанному жесту.

        Args:
            gesture_name (str): Название жеста (должно совпадать с одним из
                                поддерживаемых классов, возвращаемых детектором).
        """

    @abstractmethod
    def clear(self) -> None:
        """
        Мгновенно выключает все светодиоды на ленте.
        """

    @abstractmethod
    def set_brightness(self, value: int) -> None:
        """
        Устанавливает общую яркость свечения ленты.

        Args:
            value (int): Желаемый уровень яркости. Реализация должна самостоятельно
                         ограничивать (clamp) это значение безопасным диапазоном от 0 до 255.
        """

    @abstractmethod
    def close(self) -> None:
        """
        Корректно завершает работу с hardware и освобождает ресурсы.

        По умолчанию вызывает clear() для гарантированного выключения ленты
        перед завершением работы приложения.
        """
        self.clear()

    @abstractmethod
    def show_idle(self) -> None:
        """
        Переводит ленту в режим ожидания (idle).

        По умолчанию просто вызывает метод clear(). Может быть переопределен
        в конкретных реализациях (например, для отображения плавной анимации
        "дыхания", пока жест не распознан).
        """
        self.clear()
